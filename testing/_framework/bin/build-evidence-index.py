def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    proj, title = os.path.abspath(sys.argv[1]), sys.argv[2]
    groups = [(a.split(':')[0], a.split(':', 1)[1] if ':' in a else a.split(':')[0]) for a in sys.argv[3:]]
    body, rows, counts = [], [], {}
    for gdir, gname in groups:
        gpath = os.path.join(proj, gdir)
        if not os.path.isdir(gpath):
            continue
        subs = tests_in(gpath)
        body.append(f"## {gname}\n")
        if subs is None:
            res = render_test(proj, gpath, gname, body)
            rows.append((gname, gname, res, os.path.relpath(gpath, proj)))
            counts[res] = counts.get(res, 0) + 1
            continue
        for s in subs:
            folder = os.path.join(gpath, s)
            text = read(os.path.join(folder, 'result.md'))
            res = render_test(proj, folder, s, body)
            rows.append((gname, title_of(text, s), res, os.path.relpath(folder, proj)))
            counts[res] = counts.get(res, 0) + 1
    out = [f"# {title}: evidence\n",
           "Every test below shows its result, the pictures and links to the raw output. Generated by "
           "`testing/_framework/bin/build-evidence-index.py`; do not edit by hand.\n",
           "## Summary\n",
           "| Result | Tests |", "|---|---|"]
    for k in ('PASS', 'PARTIAL', 'FAIL', 'BLOCKED', 'NOT-RUN', 'INFO', ''):
        if k in counts:
            out.append(f"| {ICON[k]} | {counts[k]} |")
    out += ["", "| Group | Test | Result | Section |", "|---|---|---|---|"]
    for g, t, r, rel in rows:
        anchor = re.sub(r'[^a-z0-9 -]', '', t.lower()).strip().replace(' ', '-')
        out.append(f"| {g} | {t} | {ICON.get(r, r)} | [open](#{anchor}) |")
    out.append("")
    open(os.path.join(proj, 'EVIDENCE.md'), 'w').write("\n".join(out + body))
    print(f"wrote {os.path.join(proj, 'EVIDENCE.md')}: {len(rows)} tests/groups")

main()
