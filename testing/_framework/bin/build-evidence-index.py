#!/usr/bin/env python3
"""Build EVIDENCE.md: one page with every test, its result, its pictures inline and links to every output file.

Usage: build-evidence-index.py <project-dir> <title> <group-dir>[:<Group name>] ...
  <project-dir>  folder that will hold EVIDENCE.md (links are relative to it)
  <group-dir>    folder (relative to project-dir) with one sub-folder per test, each holding result.md plus
                 NN-label.txt outputs and NN-label.png pictures. A folder with no test sub-folders but a
                 result.md (for example console pages) is shown as one group.
Each result.md should contain one line `## Result: PASS` (or FAIL, PARTIAL, NOT-RUN, BLOCKED, INFO for
non-tests such as setup notes). A test without that line shows as 'no result recorded'.
"""
import os, re, sys, urllib.parse

RESULT_RE = re.compile(r'^##\s*Result:\s*\**\s*(PASS|FAIL|PARTIAL|NOT-RUN|BLOCKED|INFO)', re.M)
ICON = {'PASS': 'PASS', 'FAIL': 'FAIL', 'PARTIAL': 'PARTIAL', 'NOT-RUN': 'NOT RUN', 'BLOCKED': 'BLOCKED', 'INFO': 'info', '': 'no result recorded'}

def q(p):  # url-safe relative link
    return urllib.parse.quote(p.replace(os.sep, '/'))

def read(p):
    try:
        return open(p, errors='ignore').read()
    except OSError:
        return ''

def result_of(text):
    m = RESULT_RE.search(text)
    if m:
        return m.group(1)
    m = re.search(r'\*\*Result:?\s*(PASS|FAIL|PARTIAL|NOT-RUN|BLOCKED)', text)
    return m.group(1) if m else ''

def title_of(text, fallback):
    m = re.search(r'^#\s+(.+)$', text, re.M)
    return m.group(1).strip() if m else fallback

def field(text, name):
    m = re.search(r'-\s*\*\*%s:\*\*\s*(.+)' % name, text)
    return m.group(1).strip() if m else ''

def tests_in(group_path):
    subs = sorted(d for d in os.listdir(group_path)
                  if os.path.isdir(os.path.join(group_path, d)) and not d.startswith(('_', 'CFG')) and
                  os.path.exists(os.path.join(group_path, d, 'result.md')))
    return subs or None

def render_test(proj, folder, name, out):
    text = read(os.path.join(folder, 'result.md'))
    rel = os.path.relpath(folder, proj)
    res = result_of(text)
    out.append(f"### {title_of(text, name)}\n")
    out.append(f"**Result: {ICON.get(res, res)}** · [full notes]({q(rel + '/result.md')})\n")
    for label in ('Objective', 'Expected'):
        v = field(text, label)
        if v:
            out.append(f"- **{label}:** {v}")
    files = sorted(f for f in os.listdir(folder) if f != 'result.md' and not f.startswith('.'))
    outputs = [f for f in files if f.endswith(('.txt', '.log', '.md', '.json', '.csv', '.sh'))]
    pics = [f for f in files if f.lower().endswith(('.png', '.jpg', '.jpeg', '.webp'))]
    if outputs:
        out.append("\n**Output:** " + " · ".join(f"[{f}]({q(rel + '/' + f)})" for f in outputs))
    if pics:
        out.append("")
        for f in pics:
            label = re.sub(r'^\d+-', '', os.path.splitext(f)[0]).replace('-', ' ')
            out.append(f"**{label}**\n\n![{label}]({q(rel + '/' + f)})\n")
    out.append("\n---\n")
